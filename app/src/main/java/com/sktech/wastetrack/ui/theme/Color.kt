@Composable
fun adaptiveHarvestContainer(): Color =
    if (isSystemInDarkTheme()) DarkHarvestGreenContainer else HarvestGreenContainer

@Composable
fun adaptiveGoldenContainer(): Color =
    if (isSystemInDarkTheme()) DarkGoldenWheatContainer else GoldenWheatContainer

@Composable
fun adaptiveErrorContainer(): Color =
    if (isSystemInDarkTheme()) DarkErrorContainer else ErrorContainer

@Composable
fun adaptiveSkyBlueContainer(): Color =
    if (isSystemInDarkTheme()) DarkSkyBlueContainer else SkyBlueContainer

@Composable
fun adaptiveWarningContainer(): Color =
    if (isSystemInDarkTheme()) DarkWarningContainer else WarningContainer

